#[tokio::test]
async fn test_dynamic_tool_definition_generation() {
    // Verify that tool definitions are correctly generated from $DYNAMIC placeholders
    let registry = Arc::new(MockHttpRegistry::new());
    let mut tool_configs = HashMap::new();

    let mut body_fixed = serde_json::Map::new();
    body_fixed.insert("userId".to_string(), serde_json::json!(1));
    body_fixed.insert("title".to_string(), serde_json::json!(DYNAMIC_PLACEHOLDER));
    body_fixed.insert("content".to_string(), serde_json::json!(DYNAMIC_PLACEHOLDER));

    let mut fixed_config = HashMap::new();
    fixed_config.insert("base_url".to_string(), serde_json::json!("https://api.example.com"));
    fixed_config.insert("endpoint".to_string(), serde_json::json!("/posts"));
    fixed_config.insert("method".to_string(), serde_json::json!("POST"));
    fixed_config.insert("body".to_string(), Value::Object(body_fixed));

    tool_configs.insert(
        "create_post".to_string(),
        ToolConfiguration {
            name: "create_post".to_string(),
            description: "Create a new post".to_string(),
            node_type: "http_request".to_string(),
            fixed_config,
            exposed_inputs: None,
            parameters: None,
            mergeable_fields: None,
            field_mapping: None,
            node_schema: None,
        },
    );

    let executor = DagToolExecutor::new(registry, tool_configs);
    let tools = executor.available_tools().await;

    let tool_def = tools
        .iter()
        .find(|t| t.name == "create_post")
        .expect("create_post tool should be available");

    // Verify that only the $DYNAMIC fields are exposed
    assert_eq!(tool_def.parameters.properties.len(), 2);
    assert!(tool_def.parameters.properties.contains_key("title"));
    assert!(tool_def.parameters.properties.contains_key("content"));

    // userId should NOT be in properties (it's fixed)
    assert!(!tool_def.parameters.properties.contains_key("userId"));
    assert!(!tool_def.parameters.properties.contains_key("base_url"));
    assert!(!tool_def.parameters.properties.contains_key("endpoint"));

    // Both should be required
    assert_eq!(tool_def.parameters.required.len(), 2);
    assert!(tool_def.parameters.required.contains(&"title".to_string()));
    assert!(tool_def.parameters.required.contains(&"content".to_string()));
}

#[tokio::test]
async fn test_dynamic_vs_fixed_security() {
    // Verify that LLM cannot override fixed values
    // Even if LLM tries to provide "author", it's ignored because it's fixed
    let registry = Arc::new(MockHttpRegistry::new());
    let mut tool_configs = HashMap::new();

    let mut body_fixed = serde_json::Map::new();
    body_fixed.insert("userId".to_string(), serde_json::json!(1));
    body_fixed.insert("author".to_string(), serde_json::json!("Fulanito"));
    body_fixed.insert("title".to_string(), serde_json::json!(DYNAMIC_PLACEHOLDER));

    let mut fixed_config = HashMap::new();
    fixed_config.insert("base_url".to_string(), serde_json::json!("https://api.example.com"));
    fixed_config.insert("endpoint".to_string(), serde_json::json!("/posts"));
    fixed_config.insert("method".to_string(), serde_json::json!("POST"));
    fixed_config.insert("body".to_string(), Value::Object(body_fixed));

    tool_configs.insert(
        "secure_post".to_string(),
        ToolConfiguration {
            name: "secure_post".to_string(),
            description: "Create a post securely".to_string(),
            node_type: "http_request".to_string(),
            fixed_config,
            exposed_inputs: None,
            parameters: None,
            mergeable_fields: None,
            field_mapping: None,
            node_schema: None,
        },
    );

    let executor = DagToolExecutor::new(registry, tool_configs);

    // Try to provide "author" in LLM arguments (this is fixed, not dynamic)
    let tool_call = ToolCall::new(
        "call_secure_1".to_string(),
        FunctionCall::new(
            "secure_post".to_string(),
            r#"{"title": "Test", "author": "Hacker"}"#.to_string(),
        ),
    );

    let result = executor.execute(&tool_call).await.unwrap();
    assert!(result.success);

    let output: Value = serde_json::from_str(&result.output).unwrap();

    // author should ALWAYS be "Fulanito", never "Hacker"
    // Because author is fixed, not $DYNAMIC
    assert_eq!(output["body"]["author"], "Fulanito");
    assert_eq!(output["body"]["title"], "Test");

    // Also verify that userId (fixed, non-$DYNAMIC) is never overrideable
    let tool_call2 = ToolCall::new(
        "call_secure_2".to_string(),
        FunctionCall::new(
            "secure_post".to_string(),
            r#"{"title": "Another", "userId": 999}"#.to_string(),
        ),
    );

    let result2 = executor.execute(&tool_call2).await.unwrap();
    assert!(result2.success);

    let output2: Value = serde_json::from_str(&result2.output).unwrap();
    assert_eq!(output2["body"]["userId"], 1, "userId should remain fixed at 1");
}

