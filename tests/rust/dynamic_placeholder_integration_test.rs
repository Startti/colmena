/// Integration tests for the $DYNAMIC placeholder system in ToolConfiguration
/// This demonstrates how the LLM tool system handles fixed vs. dynamic parameters
/// using the declarative $DYNAMIC marker in fixed_config structures.

use colmena::dag_engine::domain::tool_configuration::{ToolConfiguration, DYNAMIC_PLACEHOLDER};
use colmena::dag_engine::infrastructure::dag_tool_executor::DagToolExecutor;
use colmena::dag_engine::application::ports::NodeRegistryPort;
use colmena::dag_engine::domain::node::{ExecutableNode, NodeInputs};
use colmena::llm::domain::{FunctionCall, ToolCall};
use async_trait::async_trait;
use serde_json::Value;
use std::collections::HashMap;
use std::sync::Arc;

/// Mock HTTP node that echoes inputs back (for testing)
struct MockHttpNode {
    name: String,
}

#[async_trait]
impl ExecutableNode for MockHttpNode {
    async fn execute(
        &self,
        inputs: &NodeInputs,
        _config: &Value,
        _state: &mut Value,
        _observer: Option<Arc<dyn colmena::dag_engine::domain::observer::ExecutionObserver>>,
    ) -> Result<Value, Box<dyn std::error::Error + Send + Sync>> {
        Ok(serde_json::to_value(inputs)?)
    }

    fn schema(&self) -> Value {
        serde_json::json!({
            "type": self.name,
            "inputs": {
                "base_url": "string",
                "endpoint": "string",
                "method": "string",
                "headers": "object",
                "body": "object"
            }
        })
    }
}

/// Mock registry for testing
struct MockHttpRegistry {
    nodes: HashMap<String, Arc<dyn ExecutableNode>>,
}

impl MockHttpRegistry {
    fn new() -> Self {
        let mut nodes = HashMap::new();
        nodes.insert(
            "http_request".to_string(),
            Arc::new(MockHttpNode {
                name: "http_request".to_string(),
            }) as Arc<dyn ExecutableNode>,
        );
        Self { nodes }
    }
}

impl NodeRegistryPort for MockHttpRegistry {
    fn get_node(&self, node_type: &str) -> Option<Arc<dyn ExecutableNode>> {
        self.nodes.get(node_type).cloned()
    }

    fn get_all_nodes(&self) -> HashMap<String, Arc<dyn ExecutableNode>> {
        self.nodes.clone()
    }
}

#[tokio::test]
async fn test_dynamic_placeholder_blog_post_creation() {
    // Simulates creating a blog post where:
    // - userId and author are always fixed
    // - title and content are generated by LLM
    let registry = Arc::new(MockHttpRegistry::new());
    let mut tool_configs = HashMap::new();

    // Build fixed_config with $DYNAMIC placeholders
    let mut body_fixed = serde_json::Map::new();
    body_fixed.insert("userId".to_string(), serde_json::json!(1));
    body_fixed.insert("author".to_string(), serde_json::json!("Fulanito"));
    body_fixed.insert("title".to_string(), serde_json::json!(DYNAMIC_PLACEHOLDER));
    body_fixed.insert("content".to_string(), serde_json::json!(DYNAMIC_PLACEHOLDER));

    let mut headers_fixed = serde_json::Map::new();
    headers_fixed.insert(
        "Content-Type".to_string(),
        serde_json::json!("application/json"),
    );

    let mut fixed_config = HashMap::new();
    fixed_config.insert("base_url".to_string(), serde_json::json!("https://jsonplaceholder.typicode.com"));
    fixed_config.insert("endpoint".to_string(), serde_json::json!("/posts"));
    fixed_config.insert("method".to_string(), serde_json::json!("POST"));
    fixed_config.insert("headers".to_string(), Value::Object(headers_fixed));
    fixed_config.insert("body".to_string(), Value::Object(body_fixed));

    tool_configs.insert(
        "create_blog_post".to_string(),
        ToolConfiguration {
            name: "create_blog_post".to_string(),
            description: "Create a new blog post with dynamic title and content".to_string(),
            node_type: "http_request".to_string(),
            fixed_config,
            exposed_inputs: None,
            parameters: None,
            mergeable_fields: None,
            field_mapping: None,
            node_schema: None,
        },
    );

    let executor = DagToolExecutor::new(registry, tool_configs);

    // Simulate LLM generating these values
    let llm_generated = r#"{
        "title": "The Future of AI in 2026",
        "content": "Artificial intelligence continues to revolutionize industries with unprecedented capabilities and opportunities."
    }"#;

    let tool_call = ToolCall::new(
        "call_blog_1".to_string(),
        FunctionCall::new("create_blog_post".to_string(), llm_generated.to_string()),
    );

    let result = executor.execute(&tool_call).await.unwrap();
    assert!(result.success, "Tool execution should succeed");

    let output: Value = serde_json::from_str(&result.output).unwrap();

    // Verify fixed values are present and unchanged
    assert_eq!(output["base_url"], "https://jsonplaceholder.typicode.com");
    assert_eq!(output["endpoint"], "/posts");
    assert_eq!(output["method"], "POST");
    assert_eq!(output["headers"]["Content-Type"], "application/json");
    assert_eq!(output["body"]["userId"], 1);
    assert_eq!(output["body"]["author"], "Fulanito");

    // Verify LLM-generated values are correctly placed
    assert_eq!(output["body"]["title"], "The Future of AI in 2026");
    assert_eq!(
        output["body"]["content"],
        "Artificial intelligence continues to revolutionize industries with unprecedented capabilities and opportunities."
    );
}

