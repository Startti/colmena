//! `insert_after_text`, `insert_before_text`, `insert_between` use cases.
//!
//! All three are content-addressed: the agent specifies anchor text(s);
//! the dispatcher locates them in the snapshot, computes a UTF-16
//! insertion index, converts `new_markdown` via `markdown_to_docs_ops`,
//! and POSTs one batchUpdate.
//!
//! v1 limitation: markdown containing table syntax (`|...|...|`) is
//! rejected with `InvalidArgs`. The converter's table emission is not
//! API-shaped in v1; rewriting requires a snapshot round-trip we defer
//! to v1.1. See `markdown_to_docs_ops.rs` source comments for details.

use crate::dag_engine::infrastructure::nodes::llm_synthetic_tools::markdown_to_docs_ops::{
    markdown_to_requests, InsertionPoint,
};
use crate::gdocs::application::co_edit_guard::{run_guard, GuardContext};
use crate::gdocs::domain::{
    ChangeKind, ChangeRecord, DocsError, DocumentId, DocumentSnapshot, EditResult, OutlineEntry,
    ParagraphSnapshot, Scope, TabId,
};

#[derive(Debug, Clone)]
pub struct InsertAfterTextInput {
    pub anchor: String,
    pub new_markdown: String,
    pub occurrence: Option<u32>,
}

#[derive(Debug, Clone)]
pub struct InsertBeforeTextInput {
    pub anchor: String,
    pub new_markdown: String,
    pub occurrence: Option<u32>,
}

#[derive(Debug, Clone)]
pub struct InsertBetweenInput {
    /// Heading like `"## Section A"`. Required.
    pub after_heading: String,
    /// Heading like `"## Section B"`. `None` → EOF.
    pub before_heading: Option<String>,
    pub new_markdown: String,
}

#[derive(Debug, Clone)]
pub struct InsertImageAfterTextInput {
    /// Anchor text to locate; the image is inserted right after the match.
    pub anchor: String,
    /// Publicly-accessible image URL. Google fetches it server-side, so it
    /// must be reachable without auth (PNG/JPEG/GIF, ≤50 MB, ≤2000 chars).
    pub image_url: String,
    pub occurrence: Option<u32>,
    /// Optional render size in points (PT). When both are omitted Docs uses
    /// the image's native size.
    pub width_pt: Option<f64>,
    pub height_pt: Option<f64>,
}

/// Insert after the (occurrence-th) match of `anchor` in the doc.
pub async fn run_after_text(
    ctx: &GuardContext<'_>,
    doc_id: &DocumentId,
    input: InsertAfterTextInput,
) -> Result<EditResult, DocsError> {
    reject_table_markdown(&input.new_markdown)?;
    let guard = run_guard(ctx, doc_id, &Scope::All).await?;
    let snap = &guard.snapshot;
    let (para_n, byte_off, byte_len, tab_id) = find_anchor(snap, &input.anchor, input.occurrence)?;
    let p = lookup_para(snap, para_n);
    // Insert AFTER the match: byte_off + byte_len within the paragraph.
    let after_byte = byte_off + byte_len;
    let prefix_utf16 = utf16_len(&p.text[..after_byte]);
    let index = p.start_index + prefix_utf16;

    let conversion = markdown_to_requests(
        &input.new_markdown,
        InsertionPoint::Index {
            index,
            tab_id: tab_id.clone(),
        },
    );

    apply_and_finalize(
        ctx,
        doc_id,
        snap,
        conversion.requests,
        ChangeKind::Insert,
        para_n,
        &input.new_markdown,
        tab_id,
        conversion.lossy,
        guard.soft_warnings,
    )
    .await
}

/// Insert an inline image AFTER the (occurrence-th) match of `anchor`.
///
/// Path (i) of the image-insert design: `image_url` must be a publicly
/// accessible URL (Google fetches the bytes server-side). Attachment-sourced
/// images (signed-URL or generated bytes uploaded to Drive) are deferred to
/// v1.1 — see BACKLOG "Subsystem G v1.1 → gdocs_insert_image_after_text".
///
/// Reuses the same anchor-resolution + finalize machinery as `run_after_text`;
/// only the emitted `Request` differs (`insertInlineImage` instead of
/// `insertText`).
pub async fn run_insert_image_after_text(
    ctx: &GuardContext<'_>,
    doc_id: &DocumentId,
    input: InsertImageAfterTextInput,
) -> Result<EditResult, DocsError> {
    validate_image_url(&input.image_url)?;
    let guard = run_guard(ctx, doc_id, &Scope::All).await?;
    let snap = &guard.snapshot;
    let (para_n, byte_off, byte_len, tab_id) = find_anchor(snap, &input.anchor, input.occurrence)?;
    let p = lookup_para(snap, para_n);
    // Insert AFTER the match: byte_off + byte_len within the paragraph.
    let after_byte = byte_off + byte_len;
    let prefix_utf16 = utf16_len(&p.text[..after_byte]);
    let index = p.start_index + prefix_utf16;

    let request = build_insert_image_request(
        index,
        tab_id.as_ref(),
        &input.image_url,
        input.width_pt,
        input.height_pt,
    );

    apply_and_finalize(
        ctx,
        doc_id,
        snap,
        vec![request],
        ChangeKind::Insert,
        para_n,
        &format!("[image] {}", input.image_url),
        tab_id,
        vec![], // image insert is never lossy
        guard.soft_warnings,
    )
    .await
}

/// Map an image mime to a Drive filename extension. Returns `None` for
/// non-image / unsupported mimes (Docs only accepts PNG/JPEG/GIF).
pub(crate) fn image_ext_for_mime(mime: &str) -> Option<&'static str> {
    match mime {
        "image/png" => Some("png"),
        "image/jpeg" | "image/jpg" => Some("jpg"),
        "image/gif" => Some("gif"),
        _ => None,
    }
}

/// Short non-secret token for temp filenames. Uses the process clock; collision
/// is harmless (filenames need not be unique). Avoids adding an RNG dep.
fn short_token() -> String {
    use std::time::{SystemTime, UNIX_EPOCH};
    let n = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0);
    format!("{:x}", n & 0xffff_ffff)
}

/// Insert an image from raw bytes (Approach A): upload to Drive → make public
/// → insert via the lh3 content URL → delete the temp Drive file. Returns the
/// `EditResult` plus any soft warnings (e.g. temp-file cleanup failed — the
/// insert still succeeded). Transactional: if a step AFTER the upload fails,
/// the temp Drive file is deleted before returning the error.
pub async fn run_insert_image_from_bytes(
    ctx: &GuardContext<'_>,
    doc_id: &DocumentId,
    input: InsertImageAfterTextInput,
    bytes: Vec<u8>,
    mime: &str,
) -> Result<(EditResult, Vec<String>), DocsError> {
    let ext = image_ext_for_mime(mime).ok_or_else(|| {
        DocsError::InvalidArgs(format!(
            "attachment mime '{mime}' is not a supported image (need image/png, image/jpeg, or image/gif)"
        ))
    })?;
    let filename = format!("colmena-tmp-img-{}.{ext}", short_token());
    let file_id = ctx
        .client
        .upload_image_to_drive(bytes, mime, &filename)
        .await?;

    // From here on, clean up the uploaded file if anything fails.
    if let Err(e) = ctx.client.set_anyone_reader(&file_id).await {
        let _ = ctx.client.delete_drive_file(&file_id).await;
        return Err(e);
    }
    let uri = format!("https://lh3.googleusercontent.com/d/{file_id}");
    let image_input = InsertImageAfterTextInput {
        anchor: input.anchor,
        image_url: uri,
        occurrence: input.occurrence,
        width_pt: input.width_pt,
        height_pt: input.height_pt,
    };
    let result = match run_insert_image_after_text(ctx, doc_id, image_input).await {
        Ok(r) => r,
        Err(e) => {
            let _ = ctx.client.delete_drive_file(&file_id).await;
            return Err(e);
        }
    };
    // Insert succeeded — Google has copied the image. Best-effort cleanup.
    let mut warnings = Vec::new();
    if let Err(e) = ctx.client.delete_drive_file(&file_id).await {
        warnings.push(format!(
            "image inserted OK, but the temp Drive file '{file_id}' could not be deleted: {e}"
        ));
    }
    Ok((result, warnings))
}

/// Insert before the (occurrence-th) match of `anchor`.
pub async fn run_before_text(
    ctx: &GuardContext<'_>,
    doc_id: &DocumentId,
    input: InsertBeforeTextInput,
) -> Result<EditResult, DocsError> {
    reject_table_markdown(&input.new_markdown)?;
    let guard = run_guard(ctx, doc_id, &Scope::All).await?;
    let snap = &guard.snapshot;
    let (para_n, byte_off, _byte_len, tab_id) = find_anchor(snap, &input.anchor, input.occurrence)?;
    let p = lookup_para(snap, para_n);
    let prefix_utf16 = utf16_len(&p.text[..byte_off]);
    let index = p.start_index + prefix_utf16;

    let conversion = markdown_to_requests(
        &input.new_markdown,
        InsertionPoint::Index {
            index,
            tab_id: tab_id.clone(),
        },
    );

    apply_and_finalize(
        ctx,
        doc_id,
        snap,
        conversion.requests,
        ChangeKind::Insert,
        para_n,
        &input.new_markdown,
        tab_id,
        conversion.lossy,
        guard.soft_warnings,
    )
    .await
}

/// Insert between two headings. Uses scope_resolver's BetweenHeadings
/// for paragraph-range resolution; the insertion index is the
/// `start_index` of the first paragraph after the `after_heading`
/// (existing content gets pushed down).
pub async fn run_between(
    ctx: &GuardContext<'_>,
    doc_id: &DocumentId,
    input: InsertBetweenInput,
) -> Result<EditResult, DocsError> {
    reject_table_markdown(&input.new_markdown)?;
    let scope = Scope::BetweenHeadings {
        after: input.after_heading.clone(),
        before: input.before_heading.clone(),
    };
    let guard = run_guard(ctx, doc_id, &scope).await?;
    let snap = &guard.snapshot;
    // Use the resolved scope's paragraph_start (which is the FIRST
    // paragraph AFTER the `after` heading). We insert at its
    // start_index, pushing existing content down.
    let n = guard.resolved_scope.paragraph_start;
    let p = lookup_para_or_eof(snap, n);
    let index = p.start_index;
    let tab_id = guard.resolved_scope.tab_id.clone();

    let conversion = markdown_to_requests(
        &input.new_markdown,
        InsertionPoint::Index {
            index,
            tab_id: tab_id.clone(),
        },
    );

    apply_and_finalize(
        ctx,
        doc_id,
        snap,
        conversion.requests,
        ChangeKind::Insert,
        n,
        &input.new_markdown,
        tab_id,
        conversion.lossy,
        guard.soft_warnings,
    )
    .await
}

