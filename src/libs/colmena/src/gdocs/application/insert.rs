/// Pre-scan markdown for table syntax; reject with a clear v1 message.
pub(crate) fn reject_table_markdown(md: &str) -> Result<(), DocsError> {
    // A CommonMark table requires a separator line of the form
    // `|---|---|` (with optional colons for alignment). The simplest
    // reliable check is matching that separator line — bash pipes and
    // text containing literal `|` won't trip this.
    let re = regex::Regex::new(r"(?m)^\s*\|?\s*:?-{3,}:?(\s*\|\s*:?-{3,}:?)+\s*\|?\s*$")
        .expect("static regex");
    if re.is_match(md) {
        return Err(DocsError::InvalidArgs(
            "v1 limitation: markdown tables are not supported in insert/replace use cases. \
             Use the dedicated `gdocs_insert_table` tool in v1.1, or emit the table content \
             as a regular paragraph list for now."
                .to_string(),
        ));
    }
    Ok(())
}

/// Validate the image URL before hitting the API: it must be a public
/// http(s) URL within the Docs API's 2000-char URI limit. We do NOT fetch
/// it — Google does that server-side. Attachment ids are rejected here with
/// a pointer to the (deferred) v1.1 path.
fn validate_image_url(url: &str) -> Result<(), DocsError> {
    let u = url.trim();
    if u.is_empty() {
        return Err(DocsError::InvalidArgs(
            "image_url must not be empty".to_string(),
        ));
    }
    if !(u.starts_with("http://") || u.starts_with("https://")) {
        return Err(DocsError::InvalidArgs(
            "image_url must be a public http(s) URL — Google fetches the image \
             server-side, so it has to be reachable without auth. Inserting from \
             an attachment_id (signed-URL or generated image) is not supported yet \
             (Subsystem G v1.1)."
                .to_string(),
        ));
    }
    // Docs API caps the inline-image URI at 2000 characters.
    if u.chars().count() > 2000 {
        return Err(DocsError::InvalidArgs(
            "image_url exceeds the Docs API 2000-character URI limit".to_string(),
        ));
    }
    Ok(())
}

/// Build a single `insertInlineImage` batchUpdate request. `objectSize` is
/// emitted only when at least one dimension is provided; otherwise Docs uses
/// the image's native size. The location shape mirrors `markdown_to_docs_ops::loc`.
fn build_insert_image_request(
    index: u32,
    tab_id: Option<&TabId>,
    uri: &str,
    width_pt: Option<f64>,
    height_pt: Option<f64>,
) -> serde_json::Value {
    let mut location = serde_json::Map::new();
    location.insert("index".to_string(), serde_json::json!(index));
    if let Some(t) = tab_id {
        location.insert("tabId".to_string(), serde_json::json!(t.0));
    }
    let mut img = serde_json::Map::new();
    img.insert("location".to_string(), serde_json::Value::Object(location));
    img.insert("uri".to_string(), serde_json::json!(uri.trim()));
    if width_pt.is_some() || height_pt.is_some() {
        let mut size = serde_json::Map::new();
        if let Some(w) = width_pt {
            size.insert(
                "width".to_string(),
                serde_json::json!({"magnitude": w, "unit": "PT"}),
            );
        }
        if let Some(h) = height_pt {
            size.insert(
                "height".to_string(),
                serde_json::json!({"magnitude": h, "unit": "PT"}),
            );
        }
        img.insert("objectSize".to_string(), serde_json::Value::Object(size));
    }
    serde_json::json!({ "insertInlineImage": serde_json::Value::Object(img) })
}

/// Locate the (occurrence-th) match of `anchor` in the doc. Returns
/// `(paragraph_n, byte_off_in_paragraph, byte_len, tab_id)`.
fn find_anchor(
    snap: &DocumentSnapshot,
    anchor: &str,
    occurrence: Option<u32>,
) -> Result<(u32, usize, usize, Option<TabId>), DocsError> {
    if anchor.is_empty() {
        return Err(DocsError::InvalidArgs(
            "anchor text must not be empty".to_string(),
        ));
    }
    let mut hits: Vec<(u32, usize, usize, Option<TabId>)> = Vec::new();
    for tab in &snap.tabs {
        for p in &tab.paragraphs {
            let mut start = 0;
            while let Some(rel) = p.text[start..].find(anchor) {
                let abs = start + rel;
                hits.push((p.n, abs, anchor.len(), tab.tab_id.clone()));
                start = abs + 1;
            }
        }
    }
    if hits.is_empty() {
        return Err(DocsError::TextNotFound {
            find: anchor.into(),
            fuzzy_suggestions: vec![],
        });
    }
    let n = occurrence.unwrap_or(1) as usize;
    if n == 0 || n > hits.len() {
        return Err(DocsError::TextNotFound {
            find: anchor.into(),
            fuzzy_suggestions: vec![],
        });
    }
    Ok(hits[n - 1].clone())
}

fn lookup_para(s: &DocumentSnapshot, n: u32) -> &ParagraphSnapshot {
    s.tabs
        .iter()
        .flat_map(|t| t.paragraphs.iter())
        .find(|p| p.n == n)
        .expect("paragraph exists")
}

/// Like `lookup_para`, but if `n` is past the last paragraph, returns
/// the last paragraph in the doc instead.
fn lookup_para_or_eof(s: &DocumentSnapshot, n: u32) -> &ParagraphSnapshot {
    s.tabs
        .iter()
        .flat_map(|t| t.paragraphs.iter())
        .find(|p| p.n == n)
        .or_else(|| s.tabs.iter().flat_map(|t| t.paragraphs.iter()).last())
        .expect("at least one paragraph exists")
}

fn utf16_len(s: &str) -> u32 {
    s.encode_utf16().count() as u32
}

#[allow(clippy::too_many_arguments)]
async fn apply_and_finalize(
    ctx: &GuardContext<'_>,
    doc_id: &DocumentId,
    snap: &DocumentSnapshot,
    requests: Vec<serde_json::Value>,
    kind: ChangeKind,
    paragraph: u32,
    new_markdown: &str,
    tab_id: Option<TabId>,
    lossy: Vec<crate::gdocs::domain::LossyConversion>,
    soft_warnings: Vec<crate::gdocs::domain::HumanChange>,
) -> Result<EditResult, DocsError> {
    if requests.is_empty() {
        return Err(DocsError::InvalidArgs(
            "markdown produced no batchUpdate requests (all elements were lossy)".into(),
        ));
    }
    let result = ctx
        .client
        .batch_update(doc_id, requests, Some(&snap.revision_id))
        .await?;

    // CRITICAL: store the snapshot's revision_id (documents.get format)
    // — not batch_update's writeControl id — so the next guard's
    // revisionId comparison succeeds. See replace_text.rs for the full
    // explanation.
    ctx.cache.invalidate(ctx.session_id, doc_id);
    let fresh = ctx.client.get(doc_id).await?;
    ctx.revisions
        .put_with_snapshot(ctx.session_id, doc_id, &fresh.revision_id, Some(&fresh))
        .await?;
    ctx.cache.put(ctx.session_id, doc_id, fresh.clone());

    Ok(EditResult {
        changes: vec![ChangeRecord {
            kind,
            paragraph,
            before: None,
            after: Some(new_markdown.chars().take(120).collect()),
            tab_id,
        }],
        revision_id_after: result.revision_id_after,
        outline_snapshot: build_outline(&fresh),
        lossy_conversions: lossy,
        pending_human_changes_outside_scope: soft_warnings,
    })
}

fn build_outline(s: &DocumentSnapshot) -> Vec<OutlineEntry> {
    s.tabs
        .iter()
        .flat_map(|t| {
            t.paragraphs.iter().map(|p| OutlineEntry {
                paragraph: p.n,
                tab_id: t.tab_id.clone(),
                kind: p.kind,
                text_preview: p.text.chars().take(80).collect(),
            })
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_markdown_with_table() {
        let md = "Some text\n\n| col1 | col2 |\n|------|------|\n| a    | b    |\n";
        let err = reject_table_markdown(md).unwrap_err();
        assert!(matches!(err, DocsError::InvalidArgs(_)));
    }

    #[test]
    fn accepts_markdown_without_table() {
        let md = "# Heading\n\nA paragraph.\n\n- one\n- two\n";
        assert!(reject_table_markdown(md).is_ok());
    }

    #[test]
    fn validate_image_url_accepts_public_https() {
        assert!(validate_image_url("https://example.com/cat.png").is_ok());
        assert!(validate_image_url("  http://example.com/x.jpg  ").is_ok());
    }

    #[test]
    fn validate_image_url_rejects_non_http_and_empty() {
        // attachment-id-shaped / data URIs / empty all rejected with a hint.
        assert!(matches!(
            validate_image_url("att_123"),
            Err(DocsError::InvalidArgs(_))
        ));
        assert!(matches!(
            validate_image_url("data:image/png;base64,AAAA"),
            Err(DocsError::InvalidArgs(_))
        ));
        assert!(matches!(
            validate_image_url("   "),
            Err(DocsError::InvalidArgs(_))
        ));
    }

    #[test]
    fn validate_image_url_rejects_over_2000_chars() {
        let long = format!("https://example.com/{}", "a".repeat(2000));
        assert!(matches!(
            validate_image_url(&long),
            Err(DocsError::InvalidArgs(_))
        ));
    }

    #[test]
    fn build_insert_image_request_minimal_shape() {
        let req = build_insert_image_request(42, None, "https://x.com/a.png", None, None);
        let img = &req["insertInlineImage"];
        assert_eq!(img["location"]["index"], 42);
        assert!(img["location"].get("tabId").is_none());
        assert_eq!(img["uri"], "https://x.com/a.png");
        // No size → no objectSize key (Docs uses native size).
        assert!(img.get("objectSize").is_none());
    }

    #[test]
    fn build_insert_image_request_with_tab_and_size() {
        let tab = TabId("t.1".to_string());
        let req = build_insert_image_request(
            7,
            Some(&tab),
            "https://x.com/a.png",
            Some(200.0),
            Some(150.0),
        );
        let img = &req["insertInlineImage"];
        assert_eq!(img["location"]["tabId"], "t.1");
        assert_eq!(img["objectSize"]["width"]["magnitude"], 200.0);
        assert_eq!(img["objectSize"]["width"]["unit"], "PT");
        assert_eq!(img["objectSize"]["height"]["magnitude"], 150.0);
    }

    #[test]
    fn accepts_markdown_with_literal_pipes() {
        // Pipes outside tables should NOT trigger rejection.
        let md = "Use the bash pipe operator: `ls | grep foo`\n";
        assert!(reject_table_markdown(md).is_ok());
    }
}

